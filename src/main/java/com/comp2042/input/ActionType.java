package com.comp2042.input;

/**
 * Enumeration representing the type of action or movement.
 * <p>
 * Defines the possible moves a brick can make: DOWN, LEFT, RIGHT, or ROTATE.
 * </p>
 */
public enum ActionType {
    /**
     * Move the brick down.
     */
    DOWN,
    /**
     * Move the brick left.
     */
    LEFT,
    /**
     * Move the brick right.
     */
    RIGHT,
    /**
     * Rotate the brick.
     */
    ROTATE
}
